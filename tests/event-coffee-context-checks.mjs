import assert from 'node:assert/strict';
import { eventCoffeeContext, eventCoffeeOptions } from '../lib/event-coffee-context.js';
const now=new Date('2026-11-13T11:41:00Z');
const card={id:'light',entityType:'event',title:'Light Up Wakefield',venue:'Wakefield City Centre',dates:['2026-11-13','2026-11-14'],start:'17:00',end:'21:00'};
const state={resultCards:[card],viewIds:['light'],constraints:{eventFocus:{id:'light'}}};
const context=q=>eventCoffeeContext([{role:'user',content:q}],state,now);
const usual=context('Any coffee shops in the area open at that time?');
assert.equal(usual.start,'17:00');assert.equal(usual.end,'21:00');assert.equal(usual.area,'Wakefield City Centre');
assert.deepEqual(usual.dates,card.dates);
for(const q of ['Any coffee nearby now?','Any coffee nearby tomorrow?','Any coffee in Leeds at that time?','Any coffee in Horbury at that time?','Any coffee nearby next week?','Any coffee nearby in 2027?','Any coffee nearby after the event?'])assert.equal(context(q),null,q);
assert.equal(eventCoffeeContext([{role:'user',content:'Any coffee nearby then?'}],null,now),null);
assert.deepEqual(context('Any coffee nearby then on Saturday?').dates,['2026-11-14']);
const html='<h1>Light Up at The Art House</h1><h3>13 November 2026 - 14 November 2026</h3><p>Our Coffee House will be serving warming winter drinks and festive treats throughout the event.</p><p>Opening Times</p><p>Friday 13 November (16:00-21:00)</p><p>Saturday 14 November (9.30-21:00)</p>';
let page=html;
globalThis.fetch=async()=>new Response(page);
assert.equal((await eventCoffeeOptions(usual,now)).picks.length,2);
const late=context('Any coffee nearby after 8pm?');
const lateAnswer=await eventCoffeeOptions(late,now);
assert.equal(context('Any coffee nearby after 20:30?').start,'20:30');
assert.equal(late.start,'20:00');assert.doesNotMatch(lateAnswer.reply,/HAUS/);assert.match(lateAnswer.reply,/Art House/);
assert.equal(await eventCoffeeOptions(context('Any coffee nearby at 9pm?'),now),null);
page=html.replace('2026 - 14 November 2026','2025 - 14 November 2025');
assert.doesNotMatch((await eventCoffeeOptions(usual,now)).reply,/Art House/,'An old event page cannot establish special hours');
page=html.replace('Coffee House will be serving warming winter drinks and festive treats throughout the event.','The venue opens late.');
assert.doesNotMatch((await eventCoffeeOptions(usual,now)).reply,/Art House/,'Venue opening alone cannot establish coffee service');
assert.equal(await eventCoffeeOptions({...usual,dates:['2027-11-13']},now),null);
assert.equal(eventCoffeeContext([{role:'user',content:'Any coffee nearby then?'}],state,new Date('2026-11-15T11:00:00Z')),null);
globalThis.fetch=async()=>new Response('',{status:503});
assert.equal(await eventCoffeeOptions(usual,new Date('2026-11-15T11:00:00Z')),null,'Reviewed late hours expire after the event');
console.log('Event coffee checks passed: event time/area, weekday, explicit overrides, late closing, source identity/year/service evidence and announcement expiry.');
