import assert from 'node:assert/strict';
import {canonicalMenuVenueName} from '../lib/restaurant-identities.js';
import {publishedCuisine} from '../lib/dietary-discovery.js';
import {dietaryMenuAnswer} from '../lib/practical-answers.js';
import {restaurantSetState} from '../lib/restaurant-followups.js';
import {foodChoiceFollowUp} from '../lib/food-voice.js';
assert.equal(canonicalMenuVenueName('https://tanvis.co.uk/dinner-menu/'),'Tanvi’s Indian Cuisine');
assert.equal(canonicalMenuVenueName('https://www.tanvis.co.uk/dinner-menu/'),'Tanvi’s Indian Cuisine');
assert.equal(canonicalMenuVenueName('https://tanvis.co.uk.fake-publisher.com/menu'),null);
assert.equal(canonicalMenuVenueName('https://www.hardens.com/restaurants/Wakefield/indian/'),null);
assert.equal(publishedCuisine('Tanvis indiancuisine Restaurant Wakefield'),'Indian');
assert.equal(publishedCuisine('ThaiCuisine menu'),'Thai');
assert.equal(publishedCuisine('Southindiancuisine'),'South Indian');
assert.equal(publishedCuisine('Indianola restaurant'),'');
assert.equal(publishedCuisine('Italianfoodbank'),'');
assert.equal(publishedCuisine('Tanvis indiancuisine','Thai'),null);
const sources=[{name:'Corarima',url:'https://www.corarima.co.uk/',title:'Corarima'},{name:"Valentino's Italian Restaurant",url:'https://valentinoswakefield.co.uk/menus/',title:"Valentino's Italian Restaurant"},{url:'https://tanvis.co.uk/dinner-menu/',title:'Tanvis indiancuisine Restaurant Wakefield'}];
globalThis.fetch=async url=>{
 if(String(url).includes('tanvis.co.uk'))return new Response('Unavailable',{status:403});
 const indian=String(url).includes('corarima');
 return new Response(`<title>${indian?'Corarima':"Valentino's Italian Restaurant"}</title><main><h1>${indian?'Corarima':"Valentino's Italian Restaurant"}</h1><p>${indian?'Ethiopian':'Italian'} restaurant vegetarian menu dishes.</p></main><footer>Wakefield WF1 1AA</footer>`);
};
const messages=[{role:'user',content:'Where can we eat vegetarian food in Wakefield?'}];
const evidence=[{url:sources[2].url,title:sources[2].title,text:'Tanvis indiancuisine Restaurant Wakefield. Our vegetarian menu lists dishes.'}];
const result=await dietaryMenuAnswer(messages,sources,evidence);
assert.equal(result.verification,'dietary-menu-search-evidence');assert.equal(result.sources.length,3);
assert.match(result.reply,/\*\*Tanvi’s Indian Cuisine\*\*: Indian food with vegetarian options/);
assert.doesNotMatch(result.reply,/Tanvis indiancuisine/);
assert.match(result.reply,/Which sounds more appealing: Ethiopian, Italian or Indian\?/);
assert.match(result.reply,/couldn't open the full page/,'Naming cleanup must retain the excerpt disclosure');
const state=restaurantSetState(result,{});
assert.equal(state.constraints.foodSet.entries.find(e=>e.name==='Tanvi’s Indian Cuisine').cuisine,'Indian');
const choice=foodChoiceFollowUp([{role:'user',content:"I'd prefer Indian"}],state);
assert.equal(choice.verification,'food-choice-existing');assert.equal(choice.sources.length,1);assert.equal(choice.sources[0].title,'Tanvi’s Indian Cuisine');assert.equal(choice.sources[0].url,sources[2].url);
const noDiet=await dietaryMenuAnswer(messages,[sources[2]],[{...evidence[0],text:'Tanvis indiancuisine Restaurant Wakefield. Our menu lists chicken dishes.'}]);assert.equal(noDiet.live,false,'Canonical names and cuisine labels must not supply missing dietary evidence');
console.log('Menu identity/cuisine checks passed: existing canonical name, exact own-host mapping, joined cuisine metadata, all displayed cuisines in choice question, excerpt disclosure, saved preference and no inferred dietary claims.');
